-- Уровень подготовки «Любой» (правка «Середина сентября», п.4): для разминки,
-- заминки и других модулей, которые подходят атлету любого уровня. Подбор
-- (module-selection-v3) берёт такие видео наравне с видео точного уровня.
-- Прежний вариант «Не указано» (NULL) не трогаем: такие видео по-прежнему
-- попадают только на последний фолбэк, иначе все незаполненные ролики разом
-- ушли бы во все уровни.
--
-- ВАЖНО про enum: ALTER TYPE ... ADD VALUE нельзя использовать в той же
-- транзакции, где новое значение уже применяется. Здесь 'ANY' только
-- добавляется — prisma migrate прогонит миграцию одной транзакцией без проблем.
-- Миграция аддитивная: старый код значение не пишет и строк с ним не читает.

-- AlterEnum
ALTER TYPE "Complexity" ADD VALUE IF NOT EXISTS 'ANY';

-- Досрочный финиш тренировки: статус PARTIAL — засчитаны пройденные модули
-- (каждый +20 XP + прирост характеристик), но тренировка не доведена до конца,
-- поэтому бонус +100 за полную тренировку НЕ начисляется. Ретроспективный
-- расчёт XP (gamification-server.ts) учитывает модули PARTIAL-сессий, а бонус —
-- только COMPLETED.
--
-- ВАЖНО про enum: ALTER TYPE ... ADD VALUE нельзя использовать в той же
-- транзакции, где новое значение уже применяется. Здесь 'PARTIAL' только
-- добавляется — prisma migrate прогонит миграцию одной транзакцией без проблем.
ALTER TYPE "WorkoutStatus" ADD VALUE IF NOT EXISTS 'PARTIAL';

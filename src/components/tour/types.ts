// Типы продуктового тура — интерактивного гида по реальным экранам.

export interface TourStep {
  /** Уникальный id шага (сохраняется в sessionStorage — переживает рефреш) */
  id: string;
  /** На каком маршруте должен находиться пользователь. Если не там —
   *  тур делает router.push и ждёт появления anchor (см. navigate). */
  route: string;
  /** Значение data-tour атрибута целевого элемента */
  anchor: string;
  /** Заголовок подсказки */
  title: string;
  /** Текст подсказки */
  body: string;
  /**
   * Как продвигается шаг:
   *  - 'tap'  — пользователь сам жмёт подсвеченный реальный элемент
   *             (его действие выполняется: переход/выбор/генерация).
   *  - 'next' — кнопкой «Далее» в подсказке.
   */
  advanceOn: 'tap' | 'next';
  /**
   * Как попасть на route:
   *  - 'auto' (по умолчанию) — тур сам переходит.
   *  - 'wait' — ждём, пока туда переведёт само приложение (после действия на
   *    прошлом шаге: например, сборка недели идёт несколько секунд и потом
   *    открывает календарь). Уйти самим раньше — значит оборвать эту работу.
   */
  navigate?: 'auto' | 'wait';
  /** Цели может не быть по уважительной причине (сборка недели не удалась) —
   *  тогда шаг пропускаем, а не показываем подсказку про несуществующий элемент. */
  optional?: boolean;
  /** Шаг про платную функцию: пропускается, если у пользователя paywall
   *  (иначе тап открыл бы окно подписки, а тур ушёл бы на пустой экран). */
  requiresAccess?: boolean;
  /** Последний шаг — кнопка станет «Готово» и завершит тур. */
  isLast?: boolean;
}

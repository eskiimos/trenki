// Метка (tag) web-push уведомления. В шторке телефона новое уведомление с той же
// меткой ЗАМЕНЯЕТ предыдущее. Раньше public/sw.js ставил всем пушам одну метку
// 'trenki-notification', и каждый новый пуш затирал прошлый: задание от тренера
// пропадало после нуджа про серию. Теперь метка — по типу уведомления: одинаковые
// по смыслу пуши (повторное «Серия под угрозой») заменяют друг друга, разные —
// лежат рядом.

/** Прежняя общая метка. sw.js ставит её payload'ам без метки (ручная рассылка из
 * админки, пуши, отправленные до деплоя), чтобы старое поведение не менялось. */
export const LEGACY_PUSH_TAG = 'trenki-notification';

/** Типы пушей с явной меткой. Новый сценарий — добавить сюда и передать `tag`. */
export type PushKind =
  /** Атлету: тренер назначил задание. */
  | 'assignment-new'
  /** Ребёнку: родитель дал задание (ключ — id задания: разные задания не затирают друг друга). */
  | 'parent-task-new'
  /** Тренеру: атлет закрыл задание. */
  | 'assignment-done'
  /**
   * Напоминание «через N минут тренировка» (check-workouts). Ключ — id
   * запланированной тренировки: позднее напоминание заменяет раннее (заголовки у
   * них разные, и «через 30 минут» иначе висело бы рядом уже неверным), а разные
   * тренировки друг друга не затирают.
   */
  | 'workout-soon'
  /**
   * Ежедневное напоминание по микроциклу. У текста несколько вариантов заголовка
   * (чередуются по дням), поэтому метка явная: сегодняшнее заменяет неоткрытое
   * вчерашнее с устаревшим «сегодня у тебя …».
   */
  | 'daily-reminder'
  /** Вовлекающие нуджи (engagement-nudges) — по треку: онбординг, серия, «запылились». */
  | 'nudge-onboarding'
  | 'nudge-streak'
  | 'nudge-dusty';

const TAG_PREFIX = 'trenki:';
const MAX_TAG_LENGTH = 120;

/**
 * Метка для типа пуша. `key` разводит уведомления одного типа, которые не должны
 * заменять друг друга (например, «задание выполнено» от разных атлетов у тренера).
 */
export function pushTag(kind: PushKind, key?: string | null): string {
  const k = (key ?? '').trim();
  return clip(k ? `${TAG_PREFIX}${kind}:${k}` : `${TAG_PREFIX}${kind}`);
}

/**
 * Итоговая метка для payload. Явная `tag` — как есть; без неё — по заголовку:
 * пока не все места отправки передают тип, одинаковый заголовок и есть «тот же
 * по смыслу пуш», а разные заголовки больше не затирают друг друга.
 */
export function resolvePushTag(payload: { tag?: string | null; title?: string | null }): string {
  const explicit = (payload.tag ?? '').trim();
  if (explicit) return clip(explicit);
  const title = (payload.title ?? '').trim().replace(/\s+/g, ' ').toLowerCase();
  if (!title) return LEGACY_PUSH_TAG;
  return clip(`${TAG_PREFIX}title:${title}`);
}

// Режем по символам, а не по UTF-16: в заголовках пушей эмодзи, и slice по
// длине строки мог бы разрезать суррогатную пару пополам.
function clip(tag: string): string {
  const chars = Array.from(tag);
  return chars.length > MAX_TAG_LENGTH ? chars.slice(0, MAX_TAG_LENGTH).join('') : tag;
}
